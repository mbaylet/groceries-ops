import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { mcpToolName, type McpProvider } from './provider.ts';
import type { Profile } from './profile.ts';
import { paths } from './paths.ts';

export const RULES_START = '<!-- user-rules:start -->';
export const RULES_END = '<!-- user-rules:end -->';

const sha = (v: unknown) => createHash('sha256').update(typeof v === 'string' ? v : JSON.stringify(v)).digest('hex').slice(0, 12);

export function renderTools(p: McpProvider): string {
  const search = mcpToolName(p, p.capabilities.search);
  const add = mcpToolName(p, p.capabilities.add_to_cart);
  const lines = [
    `- Load them first: ToolSearch query \`select:${search},${add}\`.`,
    `- Search: \`${search}\` (query = the item name).`,
    `- Add to cart: \`${add}\`.`,
  ];
  if (p.agent_notes) lines.push(`- Store notes: ${p.agent_notes.trim().replace(/\s+/g, ' ')}`);
  return lines.join('\n');
}

export function renderEntryLevel(p: McpProvider): string {
  const brands = p.entry_level_brands ?? [];
  const exception = 'The only exception: the user rules below explicitly allow first-price products.';
  if (brands.length === 0)
    return `This store declares no first-price range. Avoid products labelled "premier prix" / "1er prix". ${exception}`;
  return [
    `Exclude every product of these first-price (entry-level) ranges, matched case-insensitively on \`brand\` or on`,
    `the name in the title: ${brands.join(', ')}. They are the cheapest and lowest-quality ranges, so "best value`,
    `for money" never selects them. ${exception}`,
    `If only such products remain → status \`none\`, list them in \`options\` and say why in \`why\`.`,
  ].join('\n');
}

/** What the generated brief depends on besides the user's rules: template + provider-derived text. */
export function templateHash(template: string, p: McpProvider): string {
  return sha([template, renderTools(p), renderEntryLevel(p)]);
}

/** What the user-rules block was written from. */
export function rulesHash(profile: Profile, providerId: string): string {
  return sha({ text: profile.preferences_text, tags: profile.tags, provider: providerId });
}

export function renderBrief(template: string, p: McpProvider, profile: Profile, userRules: string): string {
  const body = template
    .replace('{{TOOLS}}', renderTools(p))
    .replace('{{ENTRY_LEVEL}}', renderEntryLevel(p))
    .replace('{{USER_RULES}}', `${RULES_START}\n${userRules.trim()}\n${RULES_END}`);
  const header = `<!-- generated by scripts/brief.ts — rules:${rulesHash(profile, p.id)} template:${templateHash(template, p)} -->`;
  return `${header}\n${body}`;
}

export function extractUserRules(brief: string): string | undefined {
  const a = brief.indexOf(RULES_START);
  const b = brief.indexOf(RULES_END);
  if (a < 0 || b < a) return undefined;
  return brief.slice(a + RULES_START.length, b).trim();
}

export interface BriefStatus { exists: boolean; path: string; stale: ('rules' | 'template')[]; ok: boolean }

export function briefStatus(profile: Profile, p: McpProvider): BriefStatus {
  const path = paths.productBrief();
  if (!existsSync(path)) return { exists: false, path, stale: ['rules', 'template'], ok: false };
  const text = readFileSync(path, 'utf8');
  const m = /rules:([0-9a-f]+) template:([0-9a-f]+)/.exec(text.split('\n', 1)[0] ?? '');
  const stale: BriefStatus['stale'] = [];
  if (!m || m[1] !== rulesHash(profile, p.id)) stale.push('rules');
  if (!m || m[2] !== templateHash(readFileSync(paths.briefTemplate(), 'utf8'), p)) stale.push('template');
  return { exists: true, path, stale, ok: stale.length === 0 };
}
